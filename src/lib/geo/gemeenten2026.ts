export const GEMEENTE_PREFIX = 'gemeente:' as const;
export const isGemeenteToken = (s:string):boolean => s.startsWith(GEMEENTE_PREFIX);
export const alsGemeenteToken = (naam:string):string => `${GEMEENTE_PREFIX}${naam}`;
export const gemeenteUitToken = (s:string):string => s.startsWith(GEMEENTE_PREFIX) ? s.slice(GEMEENTE_PREFIX.length) : s;
export function gemeentenVoorProvincies(provincies:readonly string[]):string[]{
 return [...new Set(provincies.flatMap(p=>GEMEENTEN_2026_PER_PROVINCIE[p]??[]))]
   .sort((a,b)=>a.localeCompare(b,'nl'));
}
export function normaliseerGemeenteNaam(s:string):string{
 const value=s.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
 return value==='s gravenhage' ? 'den haag' : value;
}
